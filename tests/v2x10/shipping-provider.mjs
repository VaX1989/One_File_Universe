import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { individualId as esmIndividualId } from '../../src/domains/v1/individuals/identity.js';
import { refineIndividuals as esmRefine } from '../../src/domains/v1/individuals/runtime.js';
globalThis.OFU={};
vm.runInThisContext(fs.readFileSync('src/domains/v1/individuals/provider.js','utf8'),{filename:'src/domains/v1/individuals/provider.js'});
const P=globalThis.OFU.v2x10Individuals;
let checks=0;const check=(v,m)=>{assert.ok(v,m);checks++;};
const key={worldId:'world-alpha',settlementId:'settlement-7',birthOrdinal:42};
assert.equal(P.individualId(key),esmIndividualId(key));checks++;
const aggregate={population:1_000_000_000,roles:['farmer','builder'],cultureConventions:['market-day'],educationTopics:['water']};
const a=P.refine({worldId:'w',settlementId:'s1',aggregate,startOrdinal:4,count:2,currentYear:30});
const b=esmRefine({worldId:'w',settlementId:'s1',aggregate,startOrdinal:4,count:2,currentYear:30});
assert.deepEqual(a.map(x=>({id:x.id,householdId:x.householdId,role:x.role,culture:x.culture,lineage:x.lineage})),b.map(x=>({id:x.id,householdId:x.householdId,role:x.role,culture:x.culture,lineage:x.lineage})));checks++;
check(P.refine({worldId:'w',settlementId:'s1',aggregate,startOrdinal:0,count:P.LIMITS.active+999}).length===P.LIMITS.active,'active working set bounded');
let person=P.appendHistoryRef(a[0],{eventId:'evt-1',provenance:'MODEL_DERIVED_SIMULATION',kind:'WITNESSED'});const retained=P.retain(person),revisited=P.refine({worldId:'w',settlementId:'s1',aggregate,startOrdinal:4,count:1,retainedById:new Map([[retained.id,retained]]),currentYear:40})[0];
assert.equal(revisited.id,person.id);assert.equal(revisited.memories[0].eventId,'evt-1');checks+=2;
const proposal=P.propose(revisited,{kind:'REQUEST_MOVE',targetId:'s2'});assert.equal(proposal.authority,'PROPOSAL_ONLY_REQUIRES_P4_ADMISSION');assert.equal(P.descriptor().canonicalMutation,false);checks+=2;
assert.equal(revisited.lineage.status,'UNKNOWN_UNLESS_RETAINED');checks++;
console.log(JSON.stringify({status:'PASS',suite:'v2x10-shipping-provider',checks,provider:P.VERSION}));
