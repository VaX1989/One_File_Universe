import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
vm.runInThisContext(fs.readFileSync(path.join(root,'src/rendering/planet/approach/approach-continuity.js'),'utf8'),{filename:'approach-continuity.js'});
const api=globalThis.OFU.v2x04ApproachContinuity;
const packet=api.makePacket({systemId:'sys-1',bodyId:'planet-1',parentBodyId:null,startDistanceRatio:5000,endDistanceRatio:1.02,samples:65,approachVector3d:[4,-2,7],surfaceTarget:{latitudeDeg:39.2,longitudeDeg:9.1},referenceFrameId:'frame-system',scaleStateToken:'semantic-system'});
assert.equal(packet.authority,'PRESENTATION_ONLY');
assert.equal(packet.scientificEvidence,false);
assert.equal(packet.frames.length,65);
assert.equal(api.validate(packet),true);
assert(packet.frames.every(f=>f.systemCanonicalEntityId==='sys-1'&&f.bodyCanonicalEntityId==='planet-1'));
assert(packet.frames.every(f=>f.cameraStateMutation===false&&f.selectionMutation===false&&f.canonicalPromotion===false));
assert(packet.frames.some(f=>f.stage==='SYSTEM'));
assert(packet.frames.some(f=>f.stage==='ORBIT'));
assert(packet.frames.some(f=>f.stage==='PLANET'));
assert(packet.frames.some(f=>f.stage==='APPROACH'));
assert(packet.frames.some(f=>f.stage==='DESCENT'));
for(let i=1;i<packet.frames.length;i++)assert(packet.frames[i].distanceRatio<packet.frames[i-1].distanceRatio);
const reverse=api.reverse(packet);
assert.equal(reverse.direction,'PROJECT_TO_SYSTEM');
assert.equal(reverse.identityInvariant.reversibleWithoutIdentitySubstitution,true);
assert.equal(reverse.frames[0].bodyCanonicalEntityId,'planet-1');
assert.deepEqual(reverse.frames[0].surfaceTarget,{latitudeDeg:39.2,longitudeDeg:9.1});
assert.deepEqual(reverse.frames.at(-1).approachVector3d,packet.frames[0].approachVector3d);
assert.throws(()=>api.makePacket({systemId:'s',bodyId:'p',startDistanceRatio:5,endDistanceRatio:8}),/invalid approach distance ratios/);
assert.throws(()=>api.makePacket({systemId:'s',bodyId:'p',startDistanceRatio:500,endDistanceRatio:1.02,samples:300}),/sample budget exceeded/);
console.log(JSON.stringify({status:'PASS',suite:'v2x04-approach-continuity-oracle',samples:packet.frames.length,stages:[...new Set(packet.frames.map(f=>f.stage))],identityStable:true,reversible:true}));
