import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
for(const rel of ['src/rendering/orbit/orbit-3d.js','src/rendering/stellar/stellar-appearance.js'])vm.runInThisContext(fs.readFileSync(path.join(root,rel),'utf8'),{filename:rel});
const orbit=globalThis.OFU.v2x04Orbit3D,stellar=globalThis.OFU.v2x04StellarAppearance;
const planet={id:'planet-a',kind:'PLANET',facts:{baselineSemiMajorAxisMicroAu:1000000,baselineEccentricityPpm:50000,baselineInclinationMilliDeg:12000}};
const moon={id:'moon-a',parentId:'planet-a',kind:'MOON',facts:{baselineSemiMajorAxisMicroAu:2500,baselineEccentricityPpm:10000,baselineInclinationMilliDeg:43000,longitudeAscendingNodeMilliDeg:120000,argumentPeriapsisMilliDeg:80000}};
const hierarchy=orbit.resolveHierarchy([planet,moon],{segments:48});
assert.equal(hierarchy.authority,'PRESENTATION_ONLY');
assert.equal(hierarchy.currentOrbitalPhaseAuthority,'UNKNOWN_NOT_CANONICAL');
assert.equal(hierarchy.nodes.length,2);
assert.equal(hierarchy.nodes[1].parentId,'planet-a');
assert(hierarchy.nodes[0].orbit.vertices.some(v=>Math.abs(v[2])>0.01),'inclined planet orbit must be genuinely 3D');
assert(hierarchy.nodes[1].orbit.vertices.some(v=>Math.abs(v[2]-hierarchy.nodes[1].orbit.center3d[2])>0.01),'inclined moon orbit must be genuinely 3D around parent anchor');
assert.equal(hierarchy.nodes[0].orbit.orientation.orientationAuthority,'PARTIAL_PRESENTATION_FALLBACK');
assert.deepEqual(hierarchy.nodes[0].orbit.orientation.unknownFields,['longitudeAscendingNode','argumentPeriapsis']);
assert.equal(hierarchy.nodes[1].orbit.orientation.orientationAuthority,'CANONICAL_PROVEN');
assert.equal(hierarchy.resourceUsage.vertices,98);
assert.throws(()=>orbit.resolveHierarchy([{...planet,parentId:'moon-a'},moon]),/cycle/);
assert.throws(()=>orbit.resolveHierarchy([{...moon,parentId:'missing'}]),/missing orbital parent/);
assert.throws(()=>orbit.buildOrbit(planet,{segments:12}),/bounded orbit budget/);
const unknown=stellar.describeStar({id:'star-unknown',facts:{}});
assert.equal(unknown.fallbackUsed,true);
assert.equal(unknown.temperature.sourceValueK,null);
assert.equal(unknown.radius.sourceValueMilliSolar,null);
assert.equal(unknown.luminosity.sourceValueMilliSolar,null);
assert.equal(unknown.scientificEvidence,false);
const known=stellar.describeStar({id:'star-known',facts:{effectiveTemperatureK:5772,radiusMilliSolar:1000,luminosityMilliSolar:1000}});
assert.equal(known.fallbackUsed,false);
assert.equal(known.temperature.cue.known,true);
assert.equal(known.radius.cue.known,true);
assert.equal(known.luminosity.cue.known,true);
assert(known.radius.cue.apparentRadiusPx>=stellar.LIMITS.minApparentRadiusPx&&known.radius.cue.apparentRadiusPx<=stellar.LIMITS.maxApparentRadiusPx);
assert(known.luminosity.cue.glowRadiusPx<=stellar.LIMITS.maxGlowRadiusPx);
assert.throws(()=>stellar.describeSystem(Array.from({length:9},(_,i)=>({id:'s'+i,facts:{}}))),/budget exceeded/);
console.log(JSON.stringify({status:'PASS',suite:'v2x04-orbit-stellar-oracle',bodies:hierarchy.resourceUsage.bodies,vertices:hierarchy.resourceUsage.vertices,phaseAuthority:hierarchy.currentOrbitalPhaseAuthority,unknownStarFallback:unknown.fallbackUsed,knownStarFallback:known.fallbackUsed}));
